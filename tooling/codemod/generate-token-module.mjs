#!/usr/bin/env node
// Generates packages/core/src/tokens.ts and the per-package copy packages/ui/src/tokens.ts (decision 42)
// from docs/agent-native/tokens.json. The copies are byte-identical apart from the header line.
//   node tooling/codemod/generate-token-module.mjs           write the files
//   node tooling/codemod/generate-token-module.mjs --check   exit 1 when a file on disk differs
// Plain constants, `as const`, no runtime logic. Values come from tokens.json only.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EXPORT_ORDER, SPACE_UNIT, TOKEN_COPIES, readModel, root, sharedTable } from "./token-model.mjs";

const DOC = {
  space: "Spacing steps. The key is a multiple of SPACE_UNIT, so `space[2]` is 8 and `space[1.5]` is 6. Negative spacing is `-space[n]`.",
  radius: "Corner radius steps in px. `radius.full` is the pill radius.",
  font: "Font size steps in px, keyed by value.",
  leading: "Line height steps in px, keyed by value.",
  border: "Border width steps in px, keyed by value (`border[1.5]`).",
  opacity: "Opacity steps keyed by percent (`opacity[45]` is 0.45). 0 and 1 are not tokens.",
  scrim: "Black overlay colours keyed by alpha percent.",
  elevation: "Box shadows. `elevation[0]` is none.",
  size: "Fixed sizes. `size.touch` is the 44 px minimum touch target.",
};
const keyText = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : /^\d+(\.\d+)?$/.test(k) ? k : JSON.stringify(k));
const valueText = (v) => (typeof v === "string" ? JSON.stringify(v) : String(v));
const numericFirst = (a, b) => (Number.isFinite(Number(a)) && Number.isFinite(Number(b)) ? Number(a) - Number(b) : Number.isFinite(Number(a)) ? -1 : Number.isFinite(Number(b)) ? 1 : a < b ? -1 : 1);

export function renderTokenModule(tokensJson, copyPath = "packages/core/src/tokens.ts") {
  const table = sharedTable(tokensJson);
  const out = [
    "// Generated by tooling/codemod/generate-token-module.mjs from docs/agent-native/tokens.json.",
    "// Do not edit by hand. Change tokens.json, regenerate, and run tooling/codemod/prove-equivalence.mjs.",
    ...(copyPath === "packages/core/src/tokens.ts" ? [] : ["// Internal copy of the core token module so this package has no runtime dependency on core. Not exported from package.json."]),
    "",
    `/** One spacing unit in px. \`space\` keys are multiples of it. */`,
    `export const SPACE_UNIT = ${SPACE_UNIT};`,
  ];
  for (const family of EXPORT_ORDER) {
    const entries = Object.entries(table[family] ?? {}).sort(([a], [b]) => numericFirst(a, b));
    if (!entries.length) throw new Error(`tokens.json has no ${family} tokens`);
    out.push("", `/** ${DOC[family]} */`, `export const ${family} = {`);
    for (const [k, v] of entries) out.push(`  ${keyText(k)}: ${valueText(v)},`);
    out.push("} as const;");
  }
  return out.join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { tokensJson } = readModel();
  let bad = 0;
  for (const rel of TOKEN_COPIES) {
    const text = renderTokenModule(tokensJson, rel);
    const target = join(root, rel);
    if (process.argv.includes("--check")) {
      let current = "";
      try { current = readFileSync(target, "utf8"); } catch { /* missing */ }
      if (current !== text) { console.error(rel + " is out of date. Run: node tooling/codemod/generate-token-module.mjs"); bad++; } else console.log(rel + " matches tokens.json");
    } else { writeFileSync(target, text); console.log("wrote " + rel); }
  }
  if (bad) process.exit(1);
}
