#!/usr/bin/env node
// Value-preserving tokenization codemod (decisions 6, 10, 12 to 14, 40).
//
//   NODE_PATH=<scratch>/node_modules node tooling/codemod/tokenize.mjs [--write] [--report <file>] [--retarget-imports]
// Packages in LOCAL_TOKEN_PACKAGES (token-model.mjs, ui) import their own packages/<pkg>/src/tokens.ts relatively.
//
// Rewrites numeric style literals in packages/*/src/**/*.{ts,tsx} to references into
// @nyc-tron/core/tokens (on-scale) or a sibling <Name>.tokens.ts (off-scale, same value).
// Without --write it only analyses. Only AST nodes that are number literals (or a unary minus
// on one) in a style position are touched. Strings, template literals, comments and Tailwind
// class names are never edited. Rerunning after --write is a no-op.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { execFileSync } from "node:child_process";
import { createAnalyzer, listSourceFiles } from "./analyze.mjs";
import { root } from "./token-model.mjs";

const args = process.argv.slice(2);
const write = args.includes("--write");
const retarget = args.includes("--retarget-imports");
const reportPath = args.includes("--report") ? args[args.indexOf("--report") + 1] : null;
const A = createAnalyzer();
const files = listSourceFiles();
const tracked = new Set(execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8", maxBuffer: 1 << 28 }).split("\n"));

if (retarget) {
  // One-off migration for files rewritten before decision 42: point `@nyc-tron/core/tokens` at the package copy.
  let n = 0;
  for (const f of files) {
    const text = readFileSync(join(root, f), "utf8");
    const want = A.tokenSpecifier(f);
    if (want === "@nyc-tron/core/tokens" || !text.includes("@nyc-tron/core/tokens")) continue;
    const out = text.replace(/(from\s+)(["'])@nyc-tron\/core\/tokens\2/g, (_, a, q) => `${a}${q}${want}${q}`);
    if (out === text) throw new Error(f + ": could not retarget");
    n++;
    if (write) writeFileSync(join(root, f), out);
  }
  console.log(`${write ? "retargeted" : "would retarget"} ${n} files`);
  process.exit(0);
}
const report = { files: files.length, changed: [], siblings: {}, replaced: {}, left: {}, leftByFile: {}, extras: [], notInMap: [] };
const bump = (o, k, n = 1) => { o[k] = (o[k] ?? 0) + n; };
const siblings = new Map(); // path -> Map(key -> value)

for (const f of files) {
  const text = readFileSync(join(root, f), "utf8");
  const a = A.analyze(f, text);
  for (const r of a.replaced) bump(report.replaced, r.category);
  for (const l of a.left) {
    bump(report.left, `${l.category}:${l.reason}`);
    (report.leftByFile[f] ??= {})[`${l.category}:${l.reason}`] = ((report.leftByFile[f] ??= {})[`${l.category}:${l.reason}`] ?? 0) + 1;
  }
  const res = A.applyRewrite(f, text, a);
  if (res) {
    report.changed.push({ file: f, replaced: a.replaced.length });
    for (const r of a.replaced) if (r.token.includes("(not in map)")) report.extras.push({ file: f, line: r.line, category: r.category, literal: r.literal });
    if (res.scoped.size) {
      const sib = A.tokensSiblingPath(f);
      if (tracked.has(sib)) throw new Error(`${sib} already exists in git, refusing to overwrite`);
      const m = siblings.get(sib) ?? new Map();
      for (const [k, v] of res.scoped) {
        if (m.has(k) && m.get(k) !== v) throw new Error(`${sib}: key ${k} has two values`);
        m.set(k, v);
      }
      siblings.set(sib, m);
    }
    if (write) writeFileSync(join(root, f), res.text);
  }
  A.forget(f);
}

const sibText = (sib, m) => {
  const name = sib.split("/").pop().replace(/\.tokens\.ts$/, "");
  const rows = [...m.entries()].sort(([x], [y]) => (x < y ? -1 : 1)).map(([k, v]) => `  ${k}: ${typeof v === "string" ? JSON.stringify(v) : v},`);
  return `// Generated by tooling/codemod/tokenize.mjs. Values are the literals ${name} used before tokenization (decision 10).\n// Scoped to this component and not exported from package.json.\nexport const tokens = {\n${rows.join("\n")}\n} as const;\n`;
};
for (const [sib, m] of siblings) {
  report.siblings[sib] = Object.fromEntries(m);
  if (write) writeFileSync(join(root, sib), sibText(sib, m));
}
report.summary = { changedFiles: report.changed.length, siblingFiles: siblings.size, replacedTotal: Object.values(report.replaced).reduce((s, n) => s + n, 0), leftTotal: Object.values(report.left).reduce((s, n) => s + n, 0) };
if (reportPath) { mkdirSync(dirname(reportPath), { recursive: true }); writeFileSync(reportPath, JSON.stringify(report, null, 1) + "\n"); }
console.log(JSON.stringify({ summary: report.summary, replaced: report.replaced, left: report.left, extras: report.extras.length }, null, 1));
console.log(write ? "WROTE changes" : "dry run: nothing written");
